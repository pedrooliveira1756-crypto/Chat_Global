# Database
# https://docs.djangoproject.com/en/6.1/ref/settings/#databases

database_url = os.environ.get('DATABASE_URL')
if database_url:
    parsed_database = urlsplit(database_url)
    if parsed_database.scheme not in ('postgres', 'postgresql') or not parsed_database.hostname or not parsed_database.path.strip('/'):
        raise ImproperlyConfigured('DATABASE_URL deve ser uma URL PostgreSQL válida.')
    DATABASES = {
        'default': {
            'ENGINE': 'django.db.backends.postgresql',
            'NAME': unquote(parsed_database.path.lstrip('/')),
            'USER': unquote(parsed_database.username or ''),
            'PASSWORD': unquote(parsed_database.password or ''),
            'HOST': parsed_database.hostname,
            'PORT': parsed_database.port or 5432,
            'CONN_MAX_AGE': 600,
            'CONN_HEALTH_CHECKS': True,
        }
    }
    sslmode = parse_qs(parsed_database.query).get('sslmode')
    if sslmode:
        DATABASES['default']['OPTIONS'] = {'sslmode': sslmode[-1]}
elif DEBUG:
    DATABASES = {
        'default': {
            'ENGINE': 'django.db.backends.sqlite3',
            'NAME': os.environ.get('CHAT_DB_PATH', BASE_DIR / 'db.sqlite3'),
            'OPTIONS': {'timeout': 20},
        }
    }
else:
    raise ImproperlyConfigured('DATABASE_URL é obrigatória em produção.')


